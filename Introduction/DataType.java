class DataType{
    public static void main(String args[]){
        int x; 
        x = 4; 
        System.out.println(x);

        double db = 2.552332;
        System.out.println(db);

        float ft = 12.433f;
        System.out.println(ft);

        char ch = 'a';
        System.out.println(ch);

        boolean bo = true;
        System.out.println(bo);

        String st = "asha";
        System.out.println(st);
    }
}